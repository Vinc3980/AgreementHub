-- Template content_schema is a data-driven TEMPLATE ENGINE DEFINITION:
--   {
--     "definitionVersion": 1,
--     "sections": [{code,title,order,guidance?,showIf?,body}],
--     "fields":   [{code,label,type,required,options?,guidance?,placeholder?,
--                   group?,default?,showIf?}]
--   }
--
--   * types: text | textarea | number | money | date | email | select | toggle
--   * body text uses {{field:CODE}} placeholders (plain text; rendered to
--     HTML/PDF downstream, never inside the engine)
--   * showIf: {"field": CODE, "equals": VALUE} makes a section/field appear
--     only when that field's value matches (e.g. deposit = "Yes")
--   * required fields block approval/signing/finalization while blank
--   * guidance is shown to editors and never appears in the document
--
-- Adding a template later = INSERT a row here (no code change), SPEC FR-2.4.
-- Definitions are validated by tests (shape, conditions and placeholder refs).

